"""Makohai's boot logo: assets/logo.png as 240 x 240, 16 colours, 4 bits a pixel (28.8 KB of flash).
Writes firmware/gen/makohai_logo.h: a palette of RGB565 colours and the packed pixels, two per byte (high nibble left)."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent


def main():
    im = Image.open(ROOT / "assets" / "logo.png").convert("RGB").resize((240, 240), Image.LANCZOS)
    q = im.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:48]
    pal += [0] * (48 - len(pal))
    rgb565 = [((pal[i] >> 3) << 11) | ((pal[i + 1] >> 2) << 5) | (pal[i + 2] >> 3) for i in range(0, 48, 3)]
    px = list(q.get_flattened_data() if hasattr(q, "get_flattened_data") else q.getdata())
    packed = [(px[i] << 4) | px[i + 1] for i in range(0, len(px), 2)]
    rows = [", ".join(f"0x{b:02X}" for b in packed[i:i + 24]) for i in range(0, len(packed), 24)]
    out = ROOT / "firmware" / "gen" / "makohai_logo.h"
    out.write_text("/* SPDX-License-Identifier: GPL-3.0-only */\n"
                   "/* generated by tools/make_logo.py from assets/logo.png: 240 x 240, 4 bits a pixel */\n"
                   "static const uint16_t LOGO_PAL[16] = {" + ", ".join(f"0x{c:04X}" for c in rgb565) + "};\n"
                   "static const uint8_t LOGO_PX[240 * 240 / 2] = {\n    " + ",\n    ".join(rows) + "\n};\n")
    q.convert("RGB").resize((480, 480), Image.NEAREST).save(ROOT / "build" / "logo-check.png") if (ROOT / "build").exists() else None
    print("->", out, f"({len(packed)} B)")


if __name__ == "__main__":
    main()
