def main():
    rows = []
    for c in range(32, 128):
        ch = chr(c)
        if ch not in G:
            ch = ch.upper() if ch.upper() in G else "?"
        art = G[ch].split("|")
        assert len(art) == 7 and all(len(r) == 5 for r in art), chr(c)
        b = [sum(1 << (4 - i) for i, ch in enumerate(r) if ch == "#") for r in art]
        rows.append("    {" + ", ".join(f"0x{x:02X}" for x in b) + f"}},   /* {chr(c) if c not in (92, 127) else 'backslash' if c == 92 else 'del'} */")
    out = Path(__file__).resolve().parent.parent / "firmware" / "gen" / "espada_font5x7.h"
    out.write_text("/* SPDX-License-Identifier: GPL-3.0-only */\n/* generated by tools/make_font5x7.py: 5x7, ASCII 32..127, bit 4 = left */\n"
                   "static const uint8_t FONT5X7[96][7] = {\n" + "\n".join(rows) + "\n};\n")
    print("->", out)


if __name__ == "__main__":
    main()
